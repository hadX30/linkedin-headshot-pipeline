class ImageGenerator:
    """Generates a professional headshot using the configured image model."""

    def __init__(self, output_dir: str | None = None):
        self.settings = Settings.from_env()
        self.output_dir = output_dir or str(self.settings.output_dir)

    def generate(self, prompt: str, face_image_path: str, output_filename: str = "headshot.png",
                 style_reference_paths: list[str] | None = None, param_overrides: dict | None = None) -> str:
        from .providers.openai_images import OpenAIImageEditor

        settings = self.settings
        if param_overrides:
            settings = dataclasses.replace(settings, generation_params={**settings.generation_params, **param_overrides})
        os.makedirs(self.output_dir, exist_ok=True)
        output_path = os.path.join(self.output_dir, output_filename)
        generated = generate(_context(settings, images=OpenAIImageEditor(settings), source=_image(face_image_path)), prompt, attempt=1)
        with open(output_path, "wb") as f:
            f.write(generated.data)
        return output_path


class MockImageGenerator:
    """A stand-in generator for testing the pipeline without the image API."""

    def __init__(self, output_dir: str | None = None):
        self.output_dir = output_dir or str(Settings.from_env().output_dir)

    def generate(self, prompt: str, face_image_path: str, output_filename: str = "headshot.png",
                 style_reference_paths: list[str] | None = None, param_overrides: dict | None = None) -> str:
        os.makedirs(self.output_dir, exist_ok=True)
        output_path = os.path.join(self.output_dir, output_filename)
        with open(output_path, "wb") as f:
            f.write(render_mock_headshot(Path(face_image_path).read_bytes(), attempt=1, label="mock image"))
        return output_path


class QualityValidator:
    """Validates a generated headshot against the original photo."""

    def __init__(self):
        from .providers.claude import ClaudeLLM

        self.settings = Settings.from_env()
        self.llm = ClaudeLLM(self.settings)
        self.client = self.llm.client

    def _load_image_as_base64(self, image_path: str) -> tuple[str, str]:
        return _load_image_as_base64(image_path)

    def validate(self, original_path: str, generated_path: str) -> dict:
        ctx = _context(self.settings, llm=self.llm, source=_image(original_path))
        return validate(ctx, _image(generated_path, ref="generated"), attempt=1)

    def _enforce_thresholds(self, report: dict) -> None:
        enforce_thresholds(report, dict(self.settings.thresholds), fail_safe=self.settings.review_fail_safe)
