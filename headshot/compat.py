"""
The original stage classes, with their original constructors and methods, for code
that imports `stages.*` directly. They run the same stage functions as the pipeline,
without tracing (each call stands alone, as before).
"""

from __future__ import annotations

import base64
import dataclasses
import os
from contextlib import contextmanager
from pathlib import Path

from .imaging import media_type_for, render_mock_headshot
from .providers import ImageInput, Providers
from .settings import Settings
from .stages import RunContext, analyze, enforce_thresholds, generate, validate, write_prompt
from .tracing import SpanRecord


class _NoTrace:
    @contextmanager
    def span(self, **_):
        yield SpanRecord()


class _Files:
    """Keeps generated bytes in memory; the classes write them where the caller asked."""

    def __init__(self):
        self.files: dict[str, bytes] = {}

    def put_file(self, run_id, name, data, content_type):  # noqa: ARG002 - store interface
        self.files[name] = data


def _image(path: str, ref: str = "input") -> ImageInput:
    return ImageInput(ref=ref, data=Path(path).read_bytes(), media_type=media_type_for(path), filename=os.path.basename(path))


def _context(settings: Settings, llm=None, images=None, source: ImageInput | None = None) -> RunContext:
    return RunContext(run_id="local", store=_Files(), tracer=_NoTrace(), providers=Providers(llm=llm, images=images),
                      source=source or ImageInput("input", b"", "image/jpeg"), thresholds=dict(settings.thresholds),
                      review_fail_safe=settings.review_fail_safe)


def _load_image_as_base64(image_path: str) -> tuple[str, str]:
    """Load an image file and return (base64_data, media_type)."""
    with open(image_path, "rb") as f:
        data = base64.standard_b64encode(f.read()).decode("utf-8")
    return data, media_type_for(image_path)


class PhotoAnalyzer:
    """Analyzes an uploaded photo using Claude Vision."""

    def __init__(self):
        from .providers.claude import ClaudeLLM

        self.settings = Settings.from_env()
        self.llm = ClaudeLLM(self.settings)
        self.client = self.llm.client

    def _load_image_as_base64(self, image_path: str) -> tuple[str, str]:
        return _load_image_as_base64(image_path)

    def analyze(self, image_path: str) -> dict:
        return analyze(_context(self.settings, llm=self.llm, source=_image(image_path)))


